# Build PetSkillScout/BossDB.lua: dungeon and raid boss NPC IDs from the
# AllTheThings Forever database (MIT, see QuestDB-LICENSE.txt).
# A boss = a numeric n(<npcID>) inside an instance file that is not under a
# QUESTS / ZONE_DROPS / RARES / VENDORS / COMMON_BOSS_DROPS header and is not
# described as a rare creature. Usage: genbosses.py <att .db> <out> <commit>
import os, re, sys
db, out, commit = sys.argv[1], sys.argv[2], sys.argv[3]
SKIP = {"QUESTS", "ZONE_DROPS", "RARES", "VENDORS", "COMMON_BOSS_DROPS", "COMMON_VENDOR_ITEMS", "TREASURES", "ACHIEVEMENTS"}
NODE = re.compile(r'^(\t*)n\(([A-Z_0-9]+)\s*,\s*\{\s*(?:--\s*(.*))?$')
ENC = re.compile(r'^(\t*)e\((\d+)\s*,\s*\{\s*(?:--\s*(.*))?$')
CID = re.compile(r'^\t*creatureID\s*=\s*(\d+)')
CRS = re.compile(r'^\t*crs\s*=\s*\{([^}]*)\}?')
CRSITEM = re.compile(r'^\t*(\d+)\s*,?\s*(?:--\s*(.*))?$')
bosses = {}
d = os.path.join(db, "forever", "dungeons & raids")
for fn in sorted(os.listdir(d)):
    if not fn.endswith(".lua") or "dungeon sets" in fn:
        continue
    lines = open(os.path.join(d, fn), encoding="utf-8").read().split("\n")
    stack = []  # (depth, name)
    enc = None  # (depth, name, skipped) of the encounter being read
    in_crs = False
    for i, line in enumerate(lines):
        # Raid encounters: e(<encounterID>, { creatureID = N / crs = {...} }).
        em = ENC.match(line)
        if em:
            depth = len(em.group(1))
            while stack and stack[-1][0] >= depth:
                stack.pop()
            enc = (depth, re.sub(r"\s*<.*?>", "", (em.group(3) or "").strip()), any(k in SKIP for _, k in stack))
            continue
        if enc and not enc[2]:
            cm = CID.match(line)
            if cm:
                bosses[int(cm.group(1))] = enc[1].replace('"', "'")
            if CRS.match(line):
                in_crs = "}" not in line
                for n in re.findall(r"\d+", CRS.match(line).group(1)):
                    bosses.setdefault(int(n), enc[1].replace('"', "'"))
                continue
            if in_crs:
                if "}" in line:
                    in_crs = False
                else:
                    im = CRSITEM.match(line)
                    if im:
                        bosses.setdefault(int(im.group(1)), (im.group(2) or enc[1]).strip().replace('"', "'"))
        m = NODE.match(line)
        if not m:
            continue
        depth, key, name = len(m.group(1)), m.group(2), (m.group(3) or "").strip()
        while stack and stack[-1][0] >= depth:
            stack.pop()
        stack.append((depth, key))
        if not key.isdigit() or any(k in SKIP for _, k in stack[:-1]):
            continue
        body = "\n".join(lines[i + 1:i + 4])
        if "Rare Creature" in body:
            continue
        bosses[int(key)] = re.sub(r"\s*<.*?>", "", name).replace('"', "'")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- Dungeon and raid bosses (NPC ID -> name), generated by tools/att/genbosses.py\n")
    f.write("-- from AllTheThings (Forever), commit %s, MIT licence (QuestDB-LICENSE.txt).\n" % commit)
    f.write("local PSS = PetSkillScout\nPSS.BossNPC = {\n")
    for k in sorted(bosses):
        f.write('[%d]="%s",\n' % (k, bosses[k]))
    f.write("}\n")
print("bosses", len(bosses))

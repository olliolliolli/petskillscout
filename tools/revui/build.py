# Build the RevUI addon from PetSkillScout's theme code.
#   python tools/revui/build.py <out dir>   (writes <out>/RevUI)
# The theme files are shared: fix them in PetSkillScout, run this again.
import os, re, shutil, sys
import lupa.lua51 as L

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "PetSkillScout")
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "..", "revui"), "RevUI")
VERSION = open(os.path.join(HERE, "VERSION")).read().strip()

# Load order matters: Skin before Bags/Inventory/Layout, Layout before the rest.
FILES = ["Profiler.lua", "BossDB.lua", "Gamepad.lua", "Skin.lua", "Bags.lua", "Inventory.lua", "SkinText.lua", "Layout.lua", "ClassPower.lua",
         "Auras.lua", "Plates.lua", "PlatesBar.lua", "GamepadTheme.lua"]
# Frame names of PetSkillScout itself that the shared code looks for: kept.
KEEP = ["PetSkillScoutMinimapButton", "PetSkillScoutGameMenuButton", "PetSkillScoutFrame"]

def transform(name, s):
    s = s.replace("local PSS = PetSkillScout", "local PSS = RevUI")
    s = s.replace("PetSkillScoutDB", "RevUIDB")
    s = s.replace("PetSkillScout_SortBags", "RevUI_SortBags").replace("BINDING_NAME_PETSKILLSCOUT_SORTBAGS", "BINDING_NAME_REVUI_SORTBAGS")
    s = s.replace("PetSkillScout" + chr(92)*2 + "Fonts", "RevUI" + chr(92)*2 + "Fonts")
    if name == "Profiler.lua":
        s = s.replace('"PetSkillScout"', '"RevUI"').replace("^PetSkillScout", "^RevUI").replace("PSS.name", "PSS.name").replace("/pss cpu", "/rev cpu")
    if name == "Inventory.lua":
        s = s.replace("PetSkillScouts", "RevUI").replace("PetSkillScout", "RevUI")
    s = s.replace("AddOns\\PetSkillScout\\\\", "AddOns\\RevUI\\\\").replace("AddOns/PetSkillScout/", "AddOns/RevUI/")
    for i, k in enumerate(KEEP):
        s = s.replace(k, "\0KEEP%d\0" % i)
    s = re.sub(r'(["\'^])PetSkillScout(?=[A-Z_"\'])', r"\1RevUI", s)
    for i, k in enumerate(KEEP):
        s = s.replace("\0KEEP%d\0" % i, k)
    if name == "Skin.lua":
        # RevUI's own theme never treats PetSkillScout as a clash.
        assert "local FULL_UI = {" in s
    head = "-- Generated by PetSkillScout/tools/revui/build.py from %s - edit it there.\n" % name
    return head + s

def locale():
    lua = L.LuaRuntime()
    lua.execute('PetSkillScout = {}; GetLocale = function() return "enUS" end')
    toc = [l.strip() for l in open(os.path.join(SRC, "PetSkillScout.toc"), encoding="utf-8")]
    for f in [l for l in toc if l.startswith("Locale")] + ["Inventory.lua", "Bags.lua", "ClassPower.lua"]:
        code = open(os.path.join(SRC, f), encoding="utf-8").read()
        if f in ("Inventory.lua", "ClassPower.lua"):
            i = code.rfind("for lang, t in pairs({")
            code = "local PSS = PetSkillScout\n" + code[i:]
        elif f == "Bags.lua":
            i = code.index("local OPT = {")
            j = code.index("\nend\n", code.index("for lang, t in pairs(OPT)")) + 5
            code = "local PSS = PetSkillScout\n" + code[i:j]
        lua.execute(code)
    loc = lua.eval("PetSkillScout.Locale")
    return {lang: loc[lang] for lang in loc.keys()}

KEYS = ["ttTameable", "rareCreature", "plateKick", "skinConflict", "skinReload", "skinReloadLater", "skinReloadNow",
        "moveCombat", "moveDone", "moveHint", "moveReset", "barPage", "dtAmmo", "dtBags", "dtDur", "dtPet",
        "xpLine", "xpRested", "xpRestedHint", "xpRestedNone", "xpResting", "happy1", "happy2", "happy3",
        "optSkinGame", "optSkinGameHint", "optSkinUnits", "optSkinUnitsHint", "optSkinBars", "optSkinBarsHint",
        "optSkinChat", "optSkinChatHint", "optChatSize", "optChatSizeHint", "optSkinMinimap", "optSkinMinimapHint",
        "optCdmAbove", "optCdmAboveHint", "optMinimapBar", "optMinimapBarHint", "optMmFree", "optMmFreeHint", "optMinimapSize", "optMinimapSizeHint",
        "optSkinPlates", "optSkinPlatesHint", "optPlateExtras", "optPlateExtrasHint", "optPlateStack", "optPlateStackHint",
        "optSkinParty", "optSkinPartyHint", "optSkinBags", "optSkinBagsHint", "optSkinFonts", "optSkinFontsHint",
        "optMove", "optMoveHint", "moveBtn", "optSkinReload", "optSkinReloadHint", "optTheme", "optThemeHint",
        "themeJournal", "themeWoW", "themeMoon", "sizeS", "sizeM", "sizeL", "sizeXL", "setInterface",
        "optOwnBags", "optOwnBagsHint", "optBagsUI", "optBagsUIHint", "optClassPower", "optClassPowerHint"]

def lua_str(v):
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\n") + '"'

def write_locale(loc):
    out = ["-- Generated by PetSkillScout/tools/revui/build.py from PetSkillScout's translations.",
           "local R = RevUI", "R.Locale = {"]
    missing = []
    for lang in sorted(loc):
        d = loc[lang]
        out.append("  %s = {" % lang)
        for k in KEYS:
            v = d[k]
            if v is None:
                if lang == "en": missing.append(k)
                continue
            if isinstance(v, str):
                v = v.replace("PetSkillScout", "RevUI")
                out.append("    %s = %s," % (k, lua_str(v)))
        out.append("  },")
    out.append("}")
    if missing:
        raise SystemExit("missing English strings: " + ", ".join(missing))
    return "\n".join(out) + "\n"

def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(os.path.join(OUT, "Fonts"))
    for f in ("NotoSans-Regular.ttf", "FONT-LICENSE.txt"):
        shutil.copy(os.path.join(SRC, "Fonts", f), os.path.join(OUT, "Fonts", f))
    shutil.copy(os.path.join(SRC, "QuestDB-LICENSE.txt"), os.path.join(OUT, "ATT-LICENSE.txt"))
    for f in ("Core.lua", "Options.lua", "LICENSE.txt", "README.txt", "Bindings.xml", "icon.tga"):
        shutil.copy(os.path.join(HERE, f), os.path.join(OUT, f))
    open(os.path.join(OUT, "Locale.lua"), "w", encoding="utf-8", newline="\n").write(write_locale(locale()))
    for f in FILES:
        s = open(os.path.join(SRC, f), encoding="utf-8").read()
        open(os.path.join(OUT, f), "w", encoding="utf-8", newline="\n").write(transform(f, s))
    toc = open(os.path.join(HERE, "RevUI.toc"), encoding="utf-8").read().replace("@VERSION@", VERSION)
    toc += "\nCore.lua\nLocale.lua\n" + "\n".join(FILES) + "\nOptions.lua\n"
    open(os.path.join(OUT, "RevUI.toc"), "w", encoding="utf-8", newline="\n").write(toc)
    # Every file must compile, and no PetSkillScout global may be left but the bridge ones.
    rt = L.LuaRuntime().eval('function(s,n) local f,e=loadstring(s,n) return e or "ok" end')
    for f in os.listdir(OUT):
        if f.endswith(".lua"):
            s = open(os.path.join(OUT, f), encoding="utf-8").read()
            r = rt(s, f)
            if r != "ok": raise SystemExit("syntax: " + r)
            for m in re.finditer(r"PetSkillScout\w*", s):
                w = m.group(0)
                if w not in KEEP and f != "Core.lua" and not s[max(0, m.start() - 3):m.start()].endswith("-- ") :
                    line = s[s.rfind("\n", 0, m.start()) + 1:s.find("\n", m.start())]
                    if not line.lstrip().startswith("--"):
                        print("check:", f, line.strip()[:120])
    print("RevUI", VERSION, "->", OUT)

main()

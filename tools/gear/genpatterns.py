"""Pattern item for each crafted item of CraftData.lua, from the ATT Forever
profession database (MIT). The addon reads the pattern's tooltip in the game
("Requires Leatherworking (140)") so the skill needed is the Forever one.
Usage: python -I tools/gear/genpatterns.py <att .contrib/.db> <CraftData.lua> <out CraftPatterns.lua> <commit>"""
import re, sys
db, craft, out, commit = sys.argv[1:5]
names = {n: int(i) for i, n in re.findall(r'\{id=(\d+),n="([^"]+)"', open(craft, encoding='utf-8').read())}
rows = {}
for prof in ('leatherworking', 'blacksmithing', 'tailoring', 'engineering'):
    for item, spell, name in re.findall(r'i\((\d+),\s*(\d+)\);\s*--\s*(.+)', open(f'{db}/forever/profession db/{prof}.lua', encoding='utf-8').read()):
        name = name.strip()
        if item != '0' and name in names and names[name] not in rows:
            rows[names[name]] = int(item)
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('-- Crafted item -> its pattern / plans item (generated by tools/gear/genpatterns.py, do not edit).\n')
    f.write(f'-- Data: AllTheThings Forever profession database, MIT licence (QuestDB-LICENSE.txt), commit {commit}.\n')
    f.write('local PSS = PetSkillScout\nPSS.CraftPatterns = {\n')
    for k in sorted(rows):
        f.write(f'  [{k}]={rows[k]},\n')
    f.write('}\n')
print('patterns', len(rows), 'of', len(names))
